export function multiply(a: number, b: number ): number{
    return a * b;
}

export function calculatePercentage(a: number, b: number): number {
    return a / b * 100;
}

export function isEven(num: number): boolean {
    return num % 2 === 0;
}

export function compareStrings(str1: string, str2: string): boolean {
    return str1 === str2;
}

export function isPositive(a: number) {
    return a > 0;
}